#!/usr/bin/env python3
"""Build the 'System' announcer for the health inventory challenge.

Reads tools/health_inventory_lines.json and writes:
  - one stereo .ogg per line into the health_inventory_voice resource pack
  - that pack's sounds.json
  - datapack/health_inventory/data/hpinv/function/voice/<event>.mcfunction,
    which picks a random line, plays it for everyone and shows it in chat

Needs ffmpeg and Piper TTS (pip install piper-tts). Reuses the voice model
cache from tools/make_voices.py.

    python3 tools/make_announcer.py          # regenerate voices and functions, then zip
    python3 tools/make_announcer.py --build  # only zip the packs into dist/
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_voices import model_paths, zip_dir  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
LINES = ROOT / "tools" / "health_inventory_lines.json"
DATAPACK = ROOT / "datapack" / "health_inventory"
VOICE_FN = DATAPACK / "data" / "hpinv" / "function" / "voice"
RESOURCEPACK = ROOT / "resourcepack" / "health_inventory_voice"
SOUNDS_DIR = RESOURCEPACK / "assets" / "hpinv" / "sounds" / "announcer"
DIST = ROOT / "dist"

# A brighter, quicker "game show AI": slight pitch up, a little chorus for the
# synthetic edge, a short room echo. Stereo, so it plays from every direction.
FILTER = (
    "asetrate=22050*1.05,aresample=44100,atempo=1.0/1.05*1.04,"
    "chorus=0.7:0.9:40|55:0.25|0.2:0.3|0.4:1.5|2.1,"
    "aecho=0.8:0.4:35:0.18,"
    "highpass=f=110,lowpass=f=10000,"
    "loudnorm=I=-14:TP=-1.5:LRA=7,"
    "apad=pad_dur=0.25"
)


def synth(text, out_ogg, onnx):
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "raw.wav"
        subprocess.run([sys.executable, "-m", "piper", "-m", str(onnx), "-f", str(wav), "--length-scale", "0.95"],
                       input=text.encode(), check=True, capture_output=True)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-af", FILTER,
                        "-ac", "2", "-ar", "44100", "-c:a", "libvorbis", "-q:a", "6", str(out_ogg)], check=True)


def snbt_string(text):
    if '"' in text or "\\" in text:
        sys.exit(f"Lines can't contain double quotes or backslashes: {text!r}")
    return text


def generate():
    events = {k: v for k, v in json.loads(LINES.read_text()).items() if not k.startswith("_")}
    onnx = model_paths()
    if SOUNDS_DIR.exists():
        shutil.rmtree(SOUNDS_DIR)
    SOUNDS_DIR.mkdir(parents=True)
    if VOICE_FN.exists():
        shutil.rmtree(VOICE_FN)
    VOICE_FN.mkdir(parents=True)

    sounds = {}
    for event, spec in events.items():
        lines = spec["lines"]
        fn = [f"# Generated by tools/make_announcer.py from tools/health_inventory_lines.json."]
        if not spec["major"]:
            fn.append("execute if score #cooldown hpinv.var matches 1.. run return fail")
        fn.append("scoreboard players set #cooldown hpinv.var 100")
        if len(lines) > 1:  # `random value 1..1` is an error, so single lines skip the pick
            fn.append(f"execute store result score #pick hpinv.var run random value 1..{len(lines)}")
        else:
            fn.append("scoreboard players set #pick hpinv.var 1")
        for i, text in enumerate(lines, 1):
            key = f"{event}.{i}"
            print(f"  {key}: {text}")
            synth(text, SOUNDS_DIR / f"{event}_{i}.ogg", onnx)
            sounds[f"announcer.{key}"] = {
                "subtitle": "subtitles.hpinv.announcer",
                "sounds": [{"name": f"hpinv:announcer/{event}_{i}"}],
            }
            fn.append(f'execute if score #pick hpinv.var matches {i} run return run function hpinv:voice/say '
                      f'{{key:"{key}",text:"{snbt_string(text)}"}}')
        (VOICE_FN / f"{event}.mcfunction").write_text("\n".join(fn) + "\n")

    (VOICE_FN / "say.mcfunction").write_text(
        "# Macro: key, text. Plays one announcer line for everyone and shows it in chat.\n"
        "$execute as @a at @s run playsound hpinv:announcer.$(key) master @s ~ ~ ~ 1 1 1\n"
        '$tellraw @a [{text:"[SYSTEM] ",color:"aqua",bold:true},{text:"$(text)",color:"white"}]\n'
    )
    (RESOURCEPACK / "assets" / "hpinv" / "sounds.json").write_text(json.dumps(sounds, indent=2) + "\n")


def build():
    DIST.mkdir(exist_ok=True)
    dp = DIST / "health_inventory_datapack.zip"
    rp = DIST / "health_inventory_resourcepack.zip"
    zip_dir(DATAPACK, dp)
    zip_dir(RESOURCEPACK, rp)
    print(f"\nBuilt {dp.relative_to(ROOT)}\nBuilt {rp.relative_to(ROOT)}")
    print(f"resource-pack-sha1={hashlib.sha1(rp.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", action="store_true", help="only zip the packs")
    if not parser.parse_args().build:
        print("Generating announcer ...")
        generate()
    build()
