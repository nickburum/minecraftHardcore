#!/usr/bin/env python3
"""Build the 'System' announcer for the mod test server's challenges.

For each challenge it reads tools/<lines file> and writes:
  - one stereo .ogg per line into the challenge's resource pack
  - that pack's sounds.json
  - datapack/<pack>/data/<ns>/function/voice/<event>.mcfunction, which picks a
    random line, plays it for everyone and shows it in chat

Both challenges run on the mod test server, which can only send players one
resource pack, so --build also zips them together as dist/modtest_resourcepack.zip.

Needs ffmpeg and Piper TTS (pip install piper-tts). Reuses the voice model
cache from tools/make_voices.py.

    python3 tools/make_announcer.py               # regenerate every challenge, then zip
    python3 tools/make_announcer.py race          # regenerate one challenge, then zip
    python3 tools/make_announcer.py --build       # only zip the packs into dist/
"""
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from make_voices import model_paths, zip_dir  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
CHALLENGES = {
    "hpinv": {"lines": "health_inventory_lines.json", "datapack": "health_inventory", "resourcepack": "health_inventory_voice"},
    "race": {"lines": "rival_race_lines.json", "datapack": "rival_race", "resourcepack": "rival_race_voice"},
}


def paths(ns):
    c = CHALLENGES[ns]
    rp = ROOT / "resourcepack" / c["resourcepack"]
    dp = ROOT / "datapack" / c["datapack"]
    return {
        "lines": ROOT / "tools" / c["lines"],
        "datapack": dp,
        "voice_fn": dp / "data" / ns / "function" / "voice",
        "resourcepack": rp,
        "sounds_dir": rp / "assets" / ns / "sounds" / "announcer",
    }

# A brighter, quicker "game show AI": slight pitch up, a little chorus for the
# synthetic edge, a short room echo. Stereo, so it plays from every direction.
FILTER = (
    "asetrate=22050*1.05,aresample=44100,atempo=1.0/1.05*1.04,"
    "chorus=0.7:0.9:40|55:0.25|0.2:0.3|0.4:1.5|2.1,"
    "aecho=0.8:0.4:35:0.18,"
    "highpass=f=110,lowpass=f=10000,"
    "loudnorm=I=-14:TP=-1.5:LRA=7,"
    "apad=pad_dur=0.25"
)


def synth(text, out_ogg, onnx):
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "raw.wav"
        subprocess.run([sys.executable, "-m", "piper", "-m", str(onnx), "-f", str(wav), "--length-scale", "0.95"],
                       input=text.encode(), check=True, capture_output=True)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-af", FILTER,
                        "-ac", "2", "-ar", "44100", "-c:a", "libvorbis", "-q:a", "6", str(out_ogg)], check=True)


def snbt_string(text):
    if '"' in text or "\\" in text:
        sys.exit(f"Lines can't contain double quotes or backslashes: {text!r}")
    return text


def generate(ns):
    P = paths(ns)
    SOUNDS_DIR, VOICE_FN, RESOURCEPACK = P["sounds_dir"], P["voice_fn"], P["resourcepack"]
    events = {k: v for k, v in json.loads(P["lines"].read_text()).items() if not k.startswith("_")}
    onnx = model_paths()
    if SOUNDS_DIR.exists():
        shutil.rmtree(SOUNDS_DIR)
    SOUNDS_DIR.mkdir(parents=True)
    if VOICE_FN.exists():
        shutil.rmtree(VOICE_FN)
    VOICE_FN.mkdir(parents=True)

    sounds = {}
    for event, spec in events.items():
        lines = spec["lines"]
        fn = [f"# Generated by tools/make_announcer.py from tools/{P['lines'].name}."]
        if not spec["major"]:
            fn.append(f"execute if score #cooldown {ns}.var matches 1.. run return fail")
        fn.append(f"scoreboard players set #cooldown {ns}.var 100")
        if len(lines) > 1:  # `random value 1..1` is an error, so single lines skip the pick
            fn.append(f"execute store result score #pick {ns}.var run random value 1..{len(lines)}")
        else:
            fn.append(f"scoreboard players set #pick {ns}.var 1")
        for i, text in enumerate(lines, 1):
            key = f"{event}.{i}"
            print(f"  {key}: {text}")
            synth(text, SOUNDS_DIR / f"{event}_{i}.ogg", onnx)
            sounds[f"announcer.{key}"] = {
                "subtitle": f"subtitles.{ns}.announcer",
                "sounds": [{"name": f"{ns}:announcer/{event}_{i}"}],
            }
            fn.append(f'execute if score #pick {ns}.var matches {i} run return run function {ns}:voice/say '
                      f'{{key:"{key}",text:"{snbt_string(text)}"}}')
        (VOICE_FN / f"{event}.mcfunction").write_text("\n".join(fn) + "\n")

    (VOICE_FN / "say.mcfunction").write_text(
        "# Macro: key, text. Plays one announcer line for everyone and shows it in chat.\n"
        f"$execute as @a at @s run playsound {ns}:announcer.$(key) master @s ~ ~ ~ 1 1 1\n"
        '$tellraw @a [{text:"[SYSTEM] ",color:"aqua",bold:true},{text:"$(text)",color:"white"}]\n'
    )
    (RESOURCEPACK / "assets" / ns / "sounds.json").write_text(json.dumps(sounds, indent=2) + "\n")


def build():
    DIST.mkdir(exist_ok=True)
    for ns, c in CHALLENGES.items():
        P = paths(ns)
        zip_dir(P["datapack"], DIST / f"{c['datapack']}_datapack.zip")
        zip_dir(P["resourcepack"], DIST / f"{c['datapack']}_resourcepack.zip")
        print(f"Built dist/{c['datapack']}_datapack.zip and dist/{c['datapack']}_resourcepack.zip")
    # One combined pack for the mod test server: every challenge's sounds, one pack.mcmeta.
    combined = DIST / "modtest_resourcepack.zip"
    with zipfile.ZipFile(combined, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("pack.mcmeta", json.dumps({"pack": {"description": [{"text": "Mod test server", "color": "gold", "bold": True}, {"text": "\nThe System announcer", "color": "aqua"}], "min_format": 69, "max_format": 97}}, indent=2))
        lang = {}
        for ns in CHALLENGES:
            rp = paths(ns)["resourcepack"]
            for path in sorted(rp.rglob("*")):
                rel = path.relative_to(rp).as_posix()
                if not path.is_file() or rel == "pack.mcmeta":
                    continue
                if rel == "assets/minecraft/lang/en_us.json":
                    lang.update(json.loads(path.read_text()))
                    continue
                z.write(path, rel)
        z.writestr("assets/minecraft/lang/en_us.json", json.dumps(lang, indent=2))
    print(f"\nBuilt dist/modtest_resourcepack.zip (all challenges, for the mod test server)")
    print(f"resource-pack-sha1={hashlib.sha1(combined.read_bytes()).hexdigest()}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("challenge", nargs="?", choices=list(CHALLENGES), help="only regenerate this challenge")
    parser.add_argument("--build", action="store_true", help="only zip the packs")
    args = parser.parse_args()
    if not args.build:
        for ns in [args.challenge] if args.challenge else CHALLENGES:
            print(f"Generating announcer for {ns} ...")
            generate(ns)
    build()
