#!/usr/bin/env python3
"""Generate the announcer voice lines for the Elixir of Life resource pack.

Needs ffmpeg and Piper TTS (pip install piper-tts). The Piper voice model is
downloaded on first run into tools/.cache.

    python3 tools/make_voices.py           # regenerate voices, then build dist/
    python3 tools/make_voices.py --build   # only zip the packs into dist/

Players listed in tools/players.txt also get their own line ("The champion,
Steve, has returned to the realm."). Everyone else gets the general line.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATAPACK = ROOT / "datapack" / "elixir_of_life"
RESOURCEPACK = ROOT / "resourcepack" / "elixir_of_life_sounds"
SOUNDS_DIR = RESOURCEPACK / "assets" / "elixir" / "sounds" / "announcer"
SOUNDS_JSON = RESOURCEPACK / "assets" / "elixir" / "sounds.json"
VOICE_MAP = DATAPACK / "data" / "elixir" / "function" / "announce" / "voice_map.mcfunction"
PLAYERS = ROOT / "tools" / "players.txt"
CACHE = ROOT / "tools" / ".cache"
DIST = ROOT / "dist"

VOICE = "en_US-ryan-high"
VOICE_URL = "https://huggingface.co/rhasspy/piper-voices/resolve/main/en/en_US/ryan/high/" + VOICE

LINES = {
    "fallen": "System message. A champion has fallen.",
    "revived": "System message. A resurrection has occurred. A champion has returned to the realm.",
}
NAMED_LINE = "System message. A resurrection has occurred. The champion, {spoken}, has returned to the realm."

# Slightly deeper voice with a hall echo, so it sounds like an announcer.
# Output is stereo: Minecraft plays stereo sounds without direction or distance
# falloff, so the announcer sounds the same everywhere, from every direction.
FILTER = (
    "asetrate=22050*0.94,aresample=44100,atempo=1.0/0.94*0.95,"
    "aecho=0.8:0.6:60|120:0.25|0.12,"
    "highpass=f=90,lowpass=f=9000,"
    "loudnorm=I=-14:TP=-1.5:LRA=7,"
    "apad=pad_dur=0.3"
)


def model_paths():
    CACHE.mkdir(parents=True, exist_ok=True)
    onnx = CACHE / f"{VOICE}.onnx"
    for path, suffix in ((onnx, ".onnx"), (Path(str(onnx) + ".json"), ".onnx.json")):
        if not path.exists():
            print(f"Downloading voice model {path.name} ...")
            urllib.request.urlretrieve(VOICE_URL + suffix, path)
    return onnx


def synth(text, out_ogg, onnx):
    with tempfile.TemporaryDirectory() as tmp:
        wav = Path(tmp) / "raw.wav"
        subprocess.run(
            [sys.executable, "-m", "piper", "-m", str(onnx), "-f", str(wav), "--length-scale", "1.08"],
            input=text.encode(), check=True, capture_output=True,
        )
        subprocess.run(
            ["ffmpeg", "-y", "-loglevel", "error", "-i", str(wav), "-af", FILTER,
             "-ac", "2", "-ar", "44100", "-c:a", "libvorbis", "-q:a", "6", str(out_ogg)],
            check=True,
        )


def read_players():
    """Lines are `Name` or `Name=how to say it`. # starts a comment."""
    players = []
    if PLAYERS.exists():
        for line in PLAYERS.read_text().splitlines():
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            name, _, spoken = line.partition("=")
            name = name.strip()
            spoken = spoken.strip() or re.sub(r"[_\d]+", " ", name).strip() or name
            if not re.fullmatch(r"[A-Za-z0-9_.]{1,16}", name):
                sys.exit(f"Not a valid Minecraft name in players.txt: {name!r}")
            players.append((name, spoken))
    return players


def sound_key(name):
    return re.sub(r"[^a-z0-9_]", "_", name.lower())


def make_voices():
    onnx = model_paths()
    if SOUNDS_DIR.exists():
        shutil.rmtree(SOUNDS_DIR)
    SOUNDS_DIR.mkdir(parents=True)

    sounds = {}
    for key, text in LINES.items():
        print(f"  {key}: {text}")
        synth(text, SOUNDS_DIR / f"{key}.ogg", onnx)
        sounds[f"announcer.{key}"] = {
            "subtitle": f"subtitles.elixir.announcer.{key}",
            "sounds": [{"name": f"elixir:announcer/{key}"}],
        }

    names = {}
    for name, spoken in read_players():
        key = sound_key(name)
        text = NAMED_LINE.format(spoken=spoken)
        print(f"  revived.{key}: {text}")
        synth(text, SOUNDS_DIR / f"revived_{key}.ogg", onnx)
        sounds[f"announcer.revived.{key}"] = {
            "subtitle": "subtitles.elixir.announcer.revived",
            "sounds": [{"name": f"elixir:announcer/revived_{key}"}],
        }
        names[name] = key

    SOUNDS_JSON.write_text(json.dumps(sounds, indent=2) + "\n")

    snbt = ",".join(f'"{n}":"{k}"' for n, k in names.items())
    VOICE_MAP.write_text(
        "# Generated by tools/make_voices.py. Maps player names to their named\n"
        "# \"has returned to the realm\" voice clip in the resource pack.\n"
        f"data modify storage elixir:voices names set value {{{snbt}}}\n"
    )


def zip_dir(src, dest):
    with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as z:
        for path in sorted(src.rglob("*")):
            if path.is_file():
                z.write(path, path.relative_to(src).as_posix())


def build():
    DIST.mkdir(exist_ok=True)
    dp = DIST / "elixir_of_life_datapack.zip"
    rp = DIST / "elixir_of_life_resourcepack.zip"
    zip_dir(DATAPACK, dp)
    zip_dir(RESOURCEPACK, rp)
    sha1 = hashlib.sha1(rp.read_bytes()).hexdigest()
    print(f"\nBuilt {dp.relative_to(ROOT)}")
    print(f"Built {rp.relative_to(ROOT)}")
    print(f"resource-pack-sha1={sha1}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--build", action="store_true", help="only zip the packs, don't regenerate voices")
    args = parser.parse_args()
    if not args.build:
        print("Generating voices ...")
        make_voices()
    build()
